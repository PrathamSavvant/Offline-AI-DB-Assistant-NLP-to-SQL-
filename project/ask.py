"""
ask.py

Phase 9 entry point — Context Generator CLI.

This is the payoff of the whole engine: it answers "which tables and joins
are relevant to this question" using ONLY the knowledge/ files already
generated by main.py (Phases 1-8). It never connects to MySQL.

That's the entire point of the project's Decision 2 — the LLM (and this
script, standing in for it) never inspects the full database, only the
pre-computed knowledge.

Usage:
    python ask.py "How many pending work orders are there in TL Group?"

    or, with no arguments, an interactive loop:
    python ask.py
"""

import json
import sys
from pathlib import Path
from typing import Any, Dict

from core.context_generator import ContextGenerator
from core.join_path_finder import JoinPathFinder
from core.logger import get_logger
from core.relationship_builder import RelationshipBuilder
from core.table_annotations import TableAnnotationStore

logger = get_logger(__name__)

from core.db_context import db_context

KNOWLEDGE_DIR = db_context.get_knowledge_dir()

REQUIRED_FILES = [
    "schema.json",
    "table_groups.json",
    "business_semantics.json",
    "table_importance.json",
]


def load_json(filename: str) -> Dict[str, Any]:
    path = KNOWLEDGE_DIR / filename
    if not path.exists():
        raise FileNotFoundError(
            f"'{path}' not found. Run `python main.py` first to generate "
            f"the knowledge base (Phases 1-8) before using ask.py."
        )
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def build_context_generator() -> ContextGenerator:
    """
    Load everything Phase 9 needs from disk and wire it together. Note:
    no Database connection happens anywhere in this function.
    """

    for filename in REQUIRED_FILES:
        if not (KNOWLEDGE_DIR / filename).exists():
            raise FileNotFoundError(
                f"Missing '{KNOWLEDGE_DIR / filename}'. Run `python main.py` "
                f"first to generate the full knowledge base."
            )

    schema = load_json("schema.json")
    grouping_data = load_json("table_groups.json")
    semantics_data = load_json("business_semantics.json")
    ranking_data = load_json("table_importance.json")
    annotations = TableAnnotationStore().get_all()

    # The relationship graph is rebuilt from schema.json rather than
    # re-reading graph.json, since RelationshipBuilder needs the live graph
    # object (with its BFS methods) rather than a static export of it.
    # This is cheap — just in-memory dict work, no DB queries.
    relationship_builder = RelationshipBuilder(schema)
    join_finder = JoinPathFinder(relationship_builder)

    return ContextGenerator(
        schema, grouping_data, semantics_data, ranking_data, join_finder,
        annotations=annotations,
    )


def answer_question(generator: ContextGenerator, question: str) -> None:
    context = generator.build_context(question)

    print(f"\nQuestion: {question}")
    print(f"Relevant tables selected: {context['selected_tables']}")

    if context["join_plan"].get("unreachable_tables"):
        print(f"Warning — could not connect: {context['join_plan']['unreachable_tables']}")

    print("\n--- Prompt ready for Ollama/Qwen ---\n")
    print(context["prompt"])
    print("--- End of prompt ---")


def main() -> None:
    try:
        generator = build_context_generator()
    except FileNotFoundError as e:
        print(f"\n{e}\n")
        sys.exit(1)

    if len(sys.argv) > 1:
        question = " ".join(sys.argv[1:])
        answer_question(generator, question)
        return

    print("Phase 9 — Context Generator (type 'exit' to quit)")
    while True:
        try:
            question = input("\nAsk a question: ").strip()
        except (EOFError, KeyboardInterrupt):
            break

        if question.lower() in ("exit", "quit"):
            break
        if not question:
            continue

        answer_question(generator, question)


if __name__ == "__main__":
    main()